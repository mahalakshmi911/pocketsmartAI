DB = "pocketsmart.db"
UPLOAD_DIR = Path("static/uploads")
UPLOAD_DIR.mkdir(parents=True, exist_ok=True)

def db():
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    return con

def init_db():
    con = db()
    con.execute("""CREATE TABLE IF NOT EXISTS users(
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL, email TEXT UNIQUE NOT NULL, password TEXT NOT NULL)""")
    con.execute("""CREATE TABLE IF NOT EXISTS history(
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        user_id INTEGER, planner TEXT, budget REAL, input_data TEXT,
        result TEXT, created_at TEXT)""")
    con.commit()
    con.close()

init_db()

def save_history(user_id, planner, budget, input_data, result):
    con = db()
    con.execute("INSERT INTO history(user_id,planner,budget,input_data,result,created_at) VALUES(?,?,?,?,?,?)",
                (user_id, planner, budget, json.dumps(input_data), json.dumps(result), datetime.now().isoformat(timespec="seconds")))
    con.commit(); con.close()

def get_user(request):
    uid = request.session.get("user_id")
    if not uid: return None
    con = db(); row = con.execute("SELECT * FROM users WHERE id=?", (uid,)).fetchone(); con.close()
    return row

