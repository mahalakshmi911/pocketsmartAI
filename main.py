async def gemini_generate(prompt, image_bytes=None, mime_type=None):
    key = os.getenv("GEMINI_API_KEY")
    if not key:
        return None
    try:
        from google import genai
        client = genai.Client(api_key=key)
        parts = [prompt]
        if image_bytes:
            parts.append({"inline_data":{"mime_type":mime_type or "image/jpeg","data":image_bytes}})
        response = client.models.generate_content(model=os.getenv("GEMINI_MODEL","gemini-2.5-flash"), contents=parts)
        text = response.text or ""
        return {"planner":"AI Recommendation","summary":text,"recommendations":[],"note":"Generated by Gemini."}
    except Exception as e:
        return {"error":str(e)}

