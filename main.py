@app.post("/generate-home", response_class=HTMLResponse)
async def generate_home(request: Request, budget: float=Form(...), room: str=Form(...), style: str=Form(...)):
    data={"budget":budget,"room":room,"style":style}
    prompt=f"Create budget-aware home interior recommendations. Budget ₹{budget}. Room: {room}. Style: {style}. Return concise item, estimated price, platform and reason."
    result=await gemini_generate(prompt)
    if not result or result.get("error"): result=fallback_home(budget,room,style)
    user=get_user(request)
    if user: save_history(user["id"],"Home",budget,data,result)
    return templates.TemplateResponse("results.html",{"request":request,"result":result,"title":"Home Recommendations","user":user})

