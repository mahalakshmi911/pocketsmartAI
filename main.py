@app.post("/generate-jewelry", response_class=HTMLResponse)
async def generate_jewelry(request: Request, budget: float=Form(...), occasion: str=Form(...), style: str=Form(...), outfit: UploadFile=File(None)):
    data={"budget":budget,"occasion":occasion,"style":style}
    image_bytes=None
    if outfit and outfit.filename:
        image_bytes=await outfit.read()
        safe=Path(outfit.filename).name
        (UPLOAD_DIR/safe).write_bytes(image_bytes)
        data["image"]=safe
    prompt=f"Recommend jewelry for occasion {occasion}, style {style}, budget ₹{budget}. Consider outfit image if provided."
    result=await gemini_generate(prompt,image_bytes,outfit.content_type if outfit else None)
    if not result or result.get("error"): result=fallback_jewelry(budget,occasion,style)
    user=get_user(request)
    if user: save_history(user["id"],"Jewelry",budget,data,result)
    return templates.TemplateResponse("results.html",{"request":request,"result":result,"title":"Jewelry Recommendations","user":user})

@app.get("/history", response_class=HTMLResponse)
def history(request: Request):
    user=get_user(request)
    if not user: return RedirectResponse("/login", status_code=303)
    con=db(); rows=con.execute("SELECT * FROM history WHERE user_id=? ORDER BY id DESC",(user["id"],)).fetchall(); con.close()
    return templates.TemplateResponse("history.html",{"request":request,"rows":rows,"user":user})

